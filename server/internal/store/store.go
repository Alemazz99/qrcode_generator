// Stesso schema per Postgres. I flag restano INTEGER 0/1 come in SQLite, così le
// query sono identiche. La Row Level Security senza regole impedisce l'accesso
// alle tabelle dalle API pubbliche di Supabase; il servizio, che ne è il
// proprietario, continua a vederle.
var pgMigrations = []string{
	`
CREATE TABLE users (
	id            BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	username      TEXT    NOT NULL,
	password_hash TEXT    NOT NULL,
	is_admin      INTEGER NOT NULL DEFAULT 0,
	disabled      INTEGER NOT NULL DEFAULT 0,
	created_at    BIGINT  NOT NULL
);
CREATE UNIQUE INDEX users_username_lower ON users (lower(username));

CREATE TABLE sessions (
	token_hash TEXT   PRIMARY KEY,
	user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	expires_at BIGINT NOT NULL
);
CREATE INDEX sessions_user ON sessions(user_id);

CREATE TABLE qr_codes (
	id         BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id    BIGINT  NOT NULL REFERENCES users(id),
	code       TEXT    NOT NULL UNIQUE,
	name       TEXT    NOT NULL DEFAULT '',
	target_url TEXT    NOT NULL,
	style_json TEXT    NOT NULL DEFAULT '{}',
	logo       BYTEA,
	logo_name  TEXT    NOT NULL DEFAULT '',
	active     INTEGER NOT NULL DEFAULT 1,
	deleted_at BIGINT,
	created_at BIGINT  NOT NULL,
	updated_at BIGINT  NOT NULL
);
CREATE INDEX qr_codes_user ON qr_codes(user_id);

CREATE TABLE target_history (
	id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	qr_id      BIGINT NOT NULL REFERENCES qr_codes(id),
	old_url    TEXT   NOT NULL,
	new_url    TEXT   NOT NULL,
	changed_at BIGINT NOT NULL,
	changed_by BIGINT REFERENCES users(id)
);
CREATE INDEX target_history_qr ON target_history(qr_id, changed_at);

CREATE TABLE scans (
	id         BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	qr_id      BIGINT  NOT NULL REFERENCES qr_codes(id),
	scanned_at BIGINT  NOT NULL,
	device     TEXT    NOT NULL,
	os         TEXT    NOT NULL,
	browser    TEXT    NOT NULL,
	is_bot     INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX scans_qr_time ON scans(qr_id, scanned_at);

ALTER TABLE users          ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions       ENABLE ROW LEVEL SECURITY;
ALTER TABLE qr_codes       ENABLE ROW LEVEL SECURITY;
ALTER TABLE target_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE scans          ENABLE ROW LEVEL SECURITY;
`,
	`ALTER TABLE qr_codes ADD COLUMN kind TEXT NOT NULL DEFAULT 'dynamic' CHECK (kind IN ('dynamic', 'static'));`,
}

func (s *Store) migrate(ctx context.Context) error {
	migrations := sqliteMigrations
	if s.db.pg {
		migrations = pgMigrations
		// Su Postgres la versione sta in una tabella; su SQLite in PRAGMA user_version
		if _, err := s.db.ExecContext(ctx,
			"CREATE TABLE IF NOT EXISTS schema_version (version INTEGER NOT NULL)"); err != nil {
			return fmt.Errorf("tabella delle versioni: %w", err)
		}
		if _, err := s.db.ExecContext(ctx,
			"ALTER TABLE schema_version ENABLE ROW LEVEL SECURITY"); err != nil {
			return fmt.Errorf("tabella delle versioni: %w", err)
		}
	}

	version, err := s.schemaVersion(ctx)
	if err != nil {
		return fmt.Errorf("lettura versione schema: %w", err)
	}
	if version > len(migrations) {
		return fmt.Errorf("il database è alla versione %d, più recente di questo eseguibile (%d)", version, len(migrations))
	}
	for i := version; i < len(migrations); i++ {
		err := s.tx(ctx, func(tx *tx) error {
			if _, err := tx.ExecContext(ctx, migrations[i]); err != nil {
				return err
			}
			if s.db.pg {
				if _, err := tx.ExecContext(ctx, "DELETE FROM schema_version"); err != nil {
					return err
				}
				_, err := tx.ExecContext(ctx, "INSERT INTO schema_version (version) VALUES (?)", i+1)
				return err
			}
			_, err := tx.ExecContext(ctx, fmt.Sprintf("PRAGMA user_version = %d", i+1))
			return err
		})
		if err != nil {
			return fmt.Errorf("migrazione %d: %w", i+1, err)
		}
	}
	return nil
}

func (s *Store) schemaVersion(ctx context.Context) (int, error) {
	var version int
	if !s.db.pg {
		err := s.db.QueryRowContext(ctx, "PRAGMA user_version").Scan(&version)
		return version, err
	}
	err := s.db.QueryRowContext(ctx, "SELECT COALESCE(MAX(version), 0) FROM schema_version").Scan(&version)
	return version, err
}

// ---- Adattamento delle query ----------------------------------------------------

// db è un *sql.DB che adatta le query al database in uso.
type db struct {
	*sql.DB
	pg bool
}

func (d *db) ExecContext(ctx context.Context, q string, args ...any) (sql.Result, error) {
	return d.DB.ExecContext(ctx, d.rebind(q), convertArgs(args)...)
}

func (d *db) QueryContext(ctx context.Context, q string, args ...any) (*sql.Rows, error) {
	return d.DB.QueryContext(ctx, d.rebind(q), convertArgs(args)...)
}

func (d *db) QueryRowContext(ctx context.Context, q string, args ...any) *sql.Row {
	return d.DB.QueryRowContext(ctx, d.rebind(q), convertArgs(args)...)
}

// tx è una transazione che adatta le query come db.
type tx struct {
	*sql.Tx
	db *db
}

func (t *tx) ExecContext(ctx context.Context, q string, args ...any) (sql.Result, error) {
	return t.Tx.ExecContext(ctx, t.db.rebind(q), convertArgs(args)...)
}

func (t *tx) QueryRowContext(ctx context.Context, q string, args ...any) *sql.Row {
	return t.Tx.QueryRowContext(ctx, t.db.rebind(q), convertArgs(args)...)
}

func (s *Store) tx(ctx context.Context, fn func(*tx) error) error {
	sqlTx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	if err := fn(&tx{Tx: sqlTx, db: s.db}); err != nil {
		sqlTx.Rollback()
		return err
	}
	return sqlTx.Commit()
}

// rebind trasforma i segnaposto "?" in "$1, $2…" per Postgres. Le query del
// pacchetto non contengono mai "?" dentro stringhe letterali.
func (d *db) rebind(q string) string {
	if !d.pg || !strings.Contains(q, "?") {
		return q
	}
	var b strings.Builder
	b.Grow(len(q) + 8)
	n := 0
	for i := 0; i < len(q); i++ {
		if q[i] == '?' {
			n++
			b.WriteByte('$')
			b.WriteString(strconv.Itoa(n))
			continue
		}
		b.WriteByte(q[i])
	}
	return b.String()
}

// convertArgs salva i booleani come 0/1: le colonne dei flag sono INTEGER su
// entrambi i database.
func convertArgs(args []any) []any {
	for i, a := range args {
		if b, ok := a.(bool); ok {
			if b {
				args[i] = int64(1)
			} else {
				args[i] = int64(0)
			}
		}
	}
	return args
}

func isUniqueViolation(err error) bool {
	if err == nil {
		return false
	}
	var pgErr *pgconn.PgError
	if errors.As(err, &pgErr) {
		return pgErr.Code == "23505"
	}
	return strings.Contains(err.Error(), "UNIQUE constraint failed")
}

func unix(t time.Time) int64 { return t.Unix() }

func fromUnix(v int64) time.Time { return time.Unix(v, 0).UTC() }

func fromNullUnix(v sql.NullInt64) *time.Time {
	if !v.Valid {
		return nil
	}
	t := fromUnix(v.Int64)
	return &t
}
