// Package store salva utenti, sessioni, QR code e scansioni su SQLite (uso
// locale, un file) oppure su Postgres (produzione, es. Supabase).
//
// Le query sono scritte una volta sola, con i segnaposto "?" e i flag come
// interi 0/1: il tipo db le adatta a Postgres ($1, $2… e booleani convertiti).
package store

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"time"

	"github.com/jackc/pgx/v5/pgconn"
	_ "github.com/jackc/pgx/v5/stdlib"
	_ "modernc.org/sqlite"
)

var (
	ErrNotFound = errors.New("non trovato")
	ErrConflict = errors.New("esiste già")
)

type Store struct {
	db *db
}

// Open apre (o crea) il database SQLite in path e applica le migrazioni mancanti.
func Open(path string) (*Store, error) {
	if dir := filepath.Dir(path); dir != "." {
		if err := os.MkdirAll(dir, 0o750); err != nil {
			return nil, fmt.Errorf("cartella del database: %w", err)
		}
	}
	dsn := "file:" + path +
		"?_pragma=foreign_keys(1)&_pragma=journal_mode(WAL)&_pragma=busy_timeout(5000)&_pragma=synchronous(NORMAL)"
	sqlDB, err := sql.Open("sqlite", dsn)
	if err != nil {
		return nil, err
	}
	// Una sola connessione: SQLite serializza comunque le scritture e così non
	// ci sono mai errori "database is locked" tra connessioni concorrenti
	sqlDB.SetMaxOpenConns(1)
	return open(&db{DB: sqlDB})
}

// OpenPostgres si collega a Postgres (url postgres://…) e applica le migrazioni mancanti.
func OpenPostgres(url string) (*Store, error) {
	sqlDB, err := sql.Open("pgx", url)
	if err != nil {
		return nil, err
	}
	// Pochi collegamenti bastano, e i pooler dei servizi gratuiti ne concedono pochi
	sqlDB.SetMaxOpenConns(5)
	sqlDB.SetMaxIdleConns(2)
	sqlDB.SetConnMaxIdleTime(5 * time.Minute)
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()
	if err := sqlDB.PingContext(ctx); err != nil {
		sqlDB.Close()
		return nil, fmt.Errorf("connessione a Postgres: %w", err)
	}
	return open(&db{DB: sqlDB, pg: true})
}

func open(d *db) (*Store, error) {
	s := &Store{db: d}
	if err := s.migrate(context.Background()); err != nil {
		d.Close()
		return nil, err
	}
	return s, nil
}

func (s *Store) Close() error { return s.db.Close() }

// Ping verifica che il database risponda (usato da /healthz).
func (s *Store) Ping(ctx context.Context) error { return s.db.PingContext(ctx) }

